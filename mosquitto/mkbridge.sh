#!/bin/sh
# mkbridge.sh — write config/conf.d/bridge-old-broker.conf: a temporary bridge to the old broker
# (the Mosquitto add-on in the Home Assistant VM), so clients can move to this broker one at a time.
#
#   ./mkbridge.sh [OLD_BROKER_ADDRESS]    default: MQTT_BROKER from ../.env (still the old broker)
#   docker compose restart                to apply
#   ./mkbridge.sh --remove && docker compose restart    when every client has moved
#
# All topics, both directions, QoS 0. `try_private` tells the old broker (also mosquitto) that this
# is a bridge, so it does not echo our own messages back: no loops. On connect the old broker sends
# its retained messages, which the bridge stores here as retained; copy_retained.py checks that.
# The file holds the password: git-ignored, uid 1883, mode 0600.
set -eu
cd "$(dirname "$0")"
OUT=config/conf.d/bridge-old-broker.conf

if [ "${1:-}" = "--remove" ]; then
    sudo rm -f "$OUT" && echo "removed $OUT"
    exit 0
fi

env_get() { grep -E "^$1=" ../.env | cut -d= -f2-; }
OLD=${1:-$(env_get MQTT_BROKER)}
PORT=$(env_get MQTT_PORT); PORT=${PORT:-1883}
U=$(env_get MQTT_USERNAME); P=$(env_get MQTT_PASSWORD)
case "$OLD" in
    ""|127.*|localhost|"$(hostname -I | cut -d' ' -f1)")
        echo "old broker address '$OLD' is this host -- pass the old broker's address as argument" >&2; exit 1 ;;
esac

TMP=$(mktemp)
cat > "$TMP" <<EOF
# Generated by mkbridge.sh -- temporary bridge to the old broker. Do not commit.
connection old-ha-broker
address ${OLD}:${PORT}
remote_username ${U}
remote_password ${P}
remote_clientid pi5new-bridge
bridge_protocol_version mqttv311
try_private true
cleansession true
start_type automatic
restart_timeout 5 30
keepalive_interval 60
notifications true
notifications_local_only true
topic # both 0
EOF
sudo install -o 1883 -g 1883 -m 0600 "$TMP" "$OUT"
rm -f "$TMP"
echo "wrote $OUT (bridge to ${OLD}:${PORT}, all topics both ways)"
